"""Report prefill and generation throughput from MLX-LM's generation path."""

import argparse
import random
import statistics
from contextlib import closing

import mlx.core as mx
from mlx_lm import load, stream_generate
from mlx_lm.sample_utils import make_sampler

from spark_mlx_llm.generation import GenerationConfig
from spark_mlx_llm.generation import make_prompt_cache as make_benchmark_cache
from spark_mlx_llm.ops.linear import LinearConfig
from spark_mlx_llm.ops.sdpa import SDPAConfig
from spark_mlx_llm.registration import register_model

__all__ = [
    "add_arguments",
    "kv_generation_options",
    "load_benchmark",
    "main",
    "run_generation",
]


def positive_int(value):
    value = int(value)
    if value < 1:
        raise argparse.ArgumentTypeError("must be a positive integer")
    return value


def add_arguments(parser):
    parser.add_argument(
        "--model", required=True, help="MLX-LM checkpoint path or HF repo"
    )
    parser.add_argument("--prompt-tokens", type=positive_int, default=2048)
    parser.add_argument(
        "--decode-tokens",
        type=positive_int,
        default=GenerationConfig.max_tokens,
        help="Number of output tokens generated by MLX-LM (EOS stopping disabled)",
    )
    GenerationConfig.add_kv_arguments(parser)
    for name in ("w8_qmv_backend", "w4_qmv_backend"):
        parser.add_argument(
            "--" + name.replace("_", "-"),
            choices=LinearConfig.choices(name),
            default=None,
        )
    for name in SDPAConfig.__dataclass_fields__:
        parser.add_argument(
            "--" + name.replace("_", "-"),
            action=argparse.BooleanOptionalAction,
            default=None,
        )


def kv_generation_options(args):
    """Shared generation settings for the benchmark, profiler and experiments."""
    options = GenerationConfig.from_options(vars(args)).kv_kwargs()
    options.pop("prefill_step_size")
    return options


def load_benchmark(args):
    if not mx.metal.is_available():
        raise ValueError("Metal GPU is unavailable")
    mx.set_default_device(mx.gpu)
    register_model()
    overrides = {
        name: value
        for name, value in vars(args).items()
        if name in (LinearConfig.__dataclass_fields__ | SDPAConfig.__dataclass_fields__)
        and value is not None
    }
    model, tokenizer, config = load(
        args.model, model_config=overrides, return_config=True
    )
    text_config = config.get("text_config", config)
    context_limit = text_config.get("max_position_embeddings")
    total = args.prompt_tokens + args.decode_tokens
    if context_limit and total > context_limit:
        raise ValueError("prompt + decode tokens exceed the model context limit")
    options = kv_generation_options(args)
    if options["kv_bits"] is not None:
        # Fail for unsupported cache layouts before warmup or measured generation.
        make_benchmark_cache(model, options["kv_quantization_scope"])
    mx.eval(model.parameters())
    # Match mlx_lm.benchmark: keep every trial at the requested output length.
    tokenizer.eos_token_ids = set()
    rng = random.Random(0)
    prompt = mx.array(
        [rng.randrange(text_config["vocab_size"]) for _ in range(args.prompt_tokens)],
        dtype=mx.uint32,
    )
    mx.eval(prompt)
    return model, tokenizer, prompt


def run_generation(
    model,
    tokenizer,
    prompt,
    decode_tokens,
    prefill_step_size,
    *,
    kv_bits=GenerationConfig.kv_bits,
    kv_group_size=32,
    quantized_kv_start=0,
    kv_quantization_scope=GenerationConfig.kv_quantization_scope,
):
    """Use the same generation and timing implementation as mlx_lm.generate."""
    generation_options = {}
    if kv_bits is not None:
        generation_options = {
            "prompt_cache": make_benchmark_cache(model, kv_quantization_scope),
            "kv_bits": kv_bits,
            "kv_group_size": kv_group_size,
            "quantized_kv_start": quantized_kv_start,
        }
    mx.synchronize()
    mx.clear_cache()
    response = None
    try:
        # Without KV quantization MLX-LM creates the fresh cache, as before.
        with closing(
            stream_generate(
                model,
                tokenizer,
                prompt,
                max_tokens=decode_tokens,
                prefill_step_size=prefill_step_size,
                sampler=make_sampler(temp=0.0),
                **generation_options,
            )
        ) as responses:
            for response in responses:
                pass
    finally:
        mx.synchronize()
    if response is None:
        raise RuntimeError("MLX-LM returned no generation statistics")
    if (
        response.generation_tokens != decode_tokens
        or response.finish_reason != "length"
    ):
        raise RuntimeError(
            f"MLX-LM generated {response.generation_tokens}/{decode_tokens} tokens "
            f"(finish_reason={response.finish_reason!r}); EOS stopping must be disabled"
        )
    return response


def main():
    parser = argparse.ArgumentParser(description="Measure prefill and decode tok/s.")
    add_arguments(parser)
    parser.add_argument("--runs", type=positive_int, default=2)
    args = parser.parse_args()
    try:
        model, tokenizer, prompt = load_benchmark(args)
    except ValueError as error:
        parser.error(str(error))

    print(
        f"Prompt: {args.prompt_tokens} tokens | Generate: {args.decode_tokens} tokens | "
        f"Prefill step: {args.prefill_step_size}",
        flush=True,
    )
    print("Generator: mlx_lm.stream_generate | Timing: MLX-LM | EOS: ignored")
    kv_options = kv_generation_options(args)
    if args.kv_bits is None:
        print("KV cache: model dtype (quantization disabled)", flush=True)
    else:
        print(
            f"KV cache: {args.kv_bits}-bit | Group: {args.kv_group_size} | "
            f"Start offset: {args.quantized_kv_start} | "
            f"Scope: {args.kv_quantization_scope}",
            flush=True,
        )
        if args.kv_quantization_scope == "full-attention":
            print("Sliding-window KV caches retain the model cache dtype.", flush=True)
    print("Warmup...", flush=True)
    run_generation(
        model,
        tokenizer,
        prompt,
        args.decode_tokens,
        args.prefill_step_size,
        **kv_options,
    )
    print(f"{'Run':>6} {'Prefill tok/s':>16} {'Generate tok/s':>16}", flush=True)
    prefill_speeds, decode_speeds = [], []
    for run in range(1, args.runs + 1):
        response = run_generation(
            model,
            tokenizer,
            prompt,
            args.decode_tokens,
            args.prefill_step_size,
            **kv_options,
        )
        prefill = response.prompt_tps
        decode = response.generation_tps
        prefill_speeds.append(prefill)
        decode_speeds.append(decode)
        print(f"{run:>6} {prefill:>16.2f} {decode:>16.2f}", flush=True)
    print(
        f"{'Median':>6} {statistics.median(prefill_speeds):>16.2f} "
        f"{statistics.median(decode_speeds):>16.2f}"
    )


if __name__ == "__main__":
    main()
