"""Metal decode sources for affine INT8 SDPA.

The short kernel uses contiguous pitches after the public API's address guard.
Keep it explicit: it must not be generated by parsing the long kernel's text.
The online softmax follows Apple MLX.
"""

_ATTENTION = r"""
const uint lane = thread_index_in_simdgroup;
const uint N = uint(length);
const uint block = thread_position_in_grid.x / 32;
const uint bh = thread_position_in_grid.y;
const uint batch = bh / (KH * (G / HPT));
const uint head = (bh / (G / HPT)) % KH;
const uint head_sub = (bh % (G / HPT)) * HPT;
const uint dim = lane * 8;
// Check actual storage strides, including capacity slices. The bound also
// covers the final unused pointer advance. Negative/wide strides retain the
// signed 64-bit path; scalar word loads need no extra view-alignment contract.
const bool narrow = (keys_strides[0] >= 0 && keys_strides[0] <= 2147483647L) &&
    (keys_strides[1] >= 0 && keys_strides[1] <= 2147483647L) &&
    (keys_strides[2] >= 0 && keys_strides[2] <= 2147483647L) &&
    (keys_strides[3] >= 0 && keys_strides[3] <= 2147483647L) &&
    (int64_t(batch) * keys_strides[0] + int64_t(head) * keys_strides[1] + (int64_t(N) + 2 * S) * keys_strides[2] + 63 * keys_strides[3] < 2147483647L) &&
    (values_strides[0] >= 0 && values_strides[0] <= 2147483647L) &&
    (values_strides[1] >= 0 && values_strides[1] <= 2147483647L) &&
    (values_strides[2] >= 0 && values_strides[2] <= 2147483647L) &&
    (values_strides[3] >= 0 && values_strides[3] <= 2147483647L) &&
    (int64_t(batch) * values_strides[0] + int64_t(head) * values_strides[1] + (int64_t(N) + 2 * S) * values_strides[2] + 63 * values_strides[3] < 2147483647L) &&
    (key_scales_strides[0] >= 0 && key_scales_strides[0] <= 2147483647L) &&
    (key_scales_strides[1] >= 0 && key_scales_strides[1] <= 2147483647L) &&
    (key_scales_strides[2] >= 0 && key_scales_strides[2] <= 2147483647L) &&
    (key_scales_strides[3] >= 0 && key_scales_strides[3] <= 2147483647L) &&
    (int64_t(batch) * key_scales_strides[0] + int64_t(head) * key_scales_strides[1] + (int64_t(N) + 2 * S) * key_scales_strides[2] + 7 * key_scales_strides[3] < 2147483647L) &&
    (key_biases_strides[0] >= 0 && key_biases_strides[0] <= 2147483647L) &&
    (key_biases_strides[1] >= 0 && key_biases_strides[1] <= 2147483647L) &&
    (key_biases_strides[2] >= 0 && key_biases_strides[2] <= 2147483647L) &&
    (key_biases_strides[3] >= 0 && key_biases_strides[3] <= 2147483647L) &&
    (int64_t(batch) * key_biases_strides[0] + int64_t(head) * key_biases_strides[1] + (int64_t(N) + 2 * S) * key_biases_strides[2] + 7 * key_biases_strides[3] < 2147483647L) &&
    (value_scales_strides[0] >= 0 && value_scales_strides[0] <= 2147483647L) &&
    (value_scales_strides[1] >= 0 && value_scales_strides[1] <= 2147483647L) &&
    (value_scales_strides[2] >= 0 && value_scales_strides[2] <= 2147483647L) &&
    (value_scales_strides[3] >= 0 && value_scales_strides[3] <= 2147483647L) &&
    (int64_t(batch) * value_scales_strides[0] + int64_t(head) * value_scales_strides[1] + (int64_t(N) + 2 * S) * value_scales_strides[2] + 7 * value_scales_strides[3] < 2147483647L) &&
    (value_biases_strides[0] >= 0 && value_biases_strides[0] <= 2147483647L) &&
    (value_biases_strides[1] >= 0 && value_biases_strides[1] <= 2147483647L) &&
    (value_biases_strides[2] >= 0 && value_biases_strides[2] <= 2147483647L) &&
    (value_biases_strides[3] >= 0 && value_biases_strides[3] <= 2147483647L) &&
    (int64_t(batch) * value_biases_strides[0] + int64_t(head) * value_biases_strides[1] + (int64_t(N) + 2 * S) * value_biases_strides[2] + 7 * value_biases_strides[3] < 2147483647L);
auto run = [&](auto offset_tag) {
    using Offset = decltype(offset_tag);
    float q[HPT][8], acc[HPT][8], qsum[HPT], m[HPT], z[HPT];
    #pragma unroll
    for (uint h = 0; h < HPT; ++h) {
        qsum[h] = 0;
        m[h] = -MAXFLOAT;
        z[h] = 0;
        #pragma unroll
        for (uint j = 0; j < 8; ++j) {
            q[h][j] = float(queries[batch * queries_strides[0] +
                (head * G + head_sub + h) * queries_strides[1] +
                (dim + j) * queries_strides[3]]) * scale;
            qsum[h] += q[h][j];
            acc[h][j] = 0;
        }
    }

    const Offset dk = S * Offset(keys_strides[2]);
    const Offset dv = S * Offset(values_strides[2]);
    const Offset dks = S * Offset(key_scales_strides[2]);
    const Offset dkb = S * Offset(key_biases_strides[2]);
    const Offset dvs = S * Offset(value_scales_strides[2]);
    const Offset dvb = S * Offset(value_biases_strides[2]);
    Offset ko = batch * Offset(keys_strides[0]) + head * Offset(keys_strides[1]) +
        block * Offset(keys_strides[2]) + (dim / 4) * Offset(keys_strides[3]);
    Offset vo = batch * Offset(values_strides[0]) + head * Offset(values_strides[1]) +
        block * Offset(values_strides[2]) + (dim / 4) * Offset(values_strides[3]);
    Offset ks = batch * Offset(key_scales_strides[0]) + head * Offset(key_scales_strides[1]) +
        block * Offset(key_scales_strides[2]) + (dim / 32) * Offset(key_scales_strides[3]);
    Offset kb = batch * Offset(key_biases_strides[0]) + head * Offset(key_biases_strides[1]) +
        block * Offset(key_biases_strides[2]) + (dim / 32) * Offset(key_biases_strides[3]);
    Offset vs = batch * Offset(value_scales_strides[0]) + head * Offset(value_scales_strides[1]) +
        block * Offset(value_scales_strides[2]) + (dim / 32) * Offset(value_scales_strides[3]);
    Offset vb = batch * Offset(value_biases_strides[0]) + head * Offset(value_biases_strides[1]) +
        block * Offset(value_biases_strides[2]) + (dim / 32) * Offset(value_biases_strides[3]);

    uint t = block;
    for (; t + S < N; t += 2 * S) {
        uint kw[2][2], vw[2][2];
        float sk[2], bk[2], sv[2], bv[2];
        #pragma unroll
        for (uint r = 0; r < 2; ++r) {
            kw[r][0] = keys[ko + r * dk];
            kw[r][1] = keys[ko + r * dk + Offset(keys_strides[3])];
            vw[r][0] = values[vo + r * dv];
            vw[r][1] = values[vo + r * dv + Offset(values_strides[3])];
            sk[r] = float(key_scales[ks + r * dks]);
            bk[r] = float(key_biases[kb + r * dkb]);
            sv[r] = float(value_scales[vs + r * dvs]);
            bv[r] = float(value_biases[vb + r * dvb]);
        }
        #pragma unroll
        for (uint r = 0; r < 2; ++r) {
            float k[8], v[8];
            #pragma unroll
            for (uint w = 0; w < 2; ++w) {
                #pragma unroll
                for (uint j = 0; j < 4; ++j) {
                    k[4 * w + j] = float((kw[r][w] >> (8 * j)) & 255);
                    v[4 * w + j] = float((vw[r][w] >> (8 * j)) & 255) * sv[r] + bv[r];
                }
            }
            #pragma unroll
            for (uint h = 0; h < HPT; ++h) {
                float score = 0;
                #pragma unroll
                for (uint j = 0; j < 8; ++j) score += q[h][j] * k[j];
                score = simd_sum(sk[r] * score + bk[r] * qsum[h]);
                const float nm = max(m[h], score);
                const float alpha = fast::exp(m[h] - nm);
                const float p = fast::exp(score - nm);
                z[h] = z[h] * alpha + p;
                m[h] = nm;
                #pragma unroll
                for (uint j = 0; j < 8; ++j) acc[h][j] = acc[h][j] * alpha + p * v[j];
            }
        }
        ko += 2 * dk;
        vo += 2 * dv;
        ks += 2 * dks;
        kb += 2 * dkb;
        vs += 2 * dvs;
        vb += 2 * dvb;
    }

    for (; t < N; t += S) {
        const float sk = float(key_scales[ks]), bk = float(key_biases[kb]);
        const float sv = float(value_scales[vs]), bv = float(value_biases[vb]);
        float k[8], v[8];
        #pragma unroll
        for (uint w = 0; w < 2; ++w) {
            const uint kw = keys[ko + w * Offset(keys_strides[3])];
            const uint vw = values[vo + w * Offset(values_strides[3])];
            #pragma unroll
            for (uint j = 0; j < 4; ++j) {
                k[4 * w + j] = float((kw >> (8 * j)) & 255);
                v[4 * w + j] = float((vw >> (8 * j)) & 255) * sv + bv;
            }
        }
        #pragma unroll
        for (uint h = 0; h < HPT; ++h) {
            float score = 0;
            #pragma unroll
            for (uint j = 0; j < 8; ++j) score += q[h][j] * k[j];
            score = simd_sum(sk * score + bk * qsum[h]);
            const float nm = max(m[h], score);
            const float alpha = fast::exp(m[h] - nm);
            const float p = fast::exp(score - nm);
            z[h] = z[h] * alpha + p;
            m[h] = nm;
            #pragma unroll
            for (uint j = 0; j < 8; ++j) acc[h][j] = acc[h][j] * alpha + p * v[j];
        }
        ko += dk;
        vo += dv;
        ks += dks;
        kb += dkb;
        vs += dvs;
        vb += dvb;
    }
    #pragma unroll
    for (uint h = 0; h < HPT; ++h) {
        const uint row = (bh * HPT + h) * S + block;
        if (lane == 0) { sums[row] = z[h]; maxs[row] = m[h]; }
        #pragma unroll
        for (uint j = 0; j < 8; ++j) partials[row * 256 + dim + j] = acc[h][j];
    }

};
if (narrow) run(int(0)); else run(int64_t(0));
"""

_SHORT_CONTIGUOUS_ATTENTION = r"""const float scale = as_type<float>(uint(SCALE_BITS));

const uint lane = thread_index_in_simdgroup;
const uint sg = thread_position_in_threadgroup.x / 32;
const uint N = uint(keys_shape[2]);
const uint bh = thread_position_in_grid.y;
const uint batch = bh / (KH * (G / HPT));
const uint head = (bh / (G / HPT)) % KH;
const uint head_sub = (bh % (G / HPT)) * HPT;
const uint dim = lane * 8;
threadgroup float scratch[HPT * MW * 32 * NS];
threadgroup float max_scores[HPT * NS];
threadgroup float sum_scores[HPT * NS];
auto run = [&](auto offset_tag) {
    using Offset = decltype(offset_tag);
    float q[HPT][8], acc[HPT][8], qsum[HPT], m[HPT], z[HPT];
    #pragma unroll
    for (uint h = 0; h < HPT; ++h) {
        qsum[h] = 0;
        m[h] = -MAXFLOAT;
        z[h] = 0;
        #pragma unroll
        for (uint j = 0; j < 8; ++j) {
            q[h][j] = float(queries[batch * (KH * G * 256) +
                (head * G + head_sub + h) * 256 +
                (dim + j) * 1]) * scale;
            qsum[h] += q[h][j];
            acc[h][j] = 0;
        }
    }
    const Offset dk = NS * Offset(64);
    const Offset dv = NS * Offset(64);
    const Offset dks = NS * Offset(8);
    const Offset dkb = NS * Offset(8);
    const Offset dvs = NS * Offset(8);
    const Offset dvb = NS * Offset(8);
    Offset ko = batch * Offset((KH * N * 64)) + head * Offset((N * 64)) +
        sg * Offset(64) + (dim / 4) * Offset(1);
    Offset vo = batch * Offset((KH * N * 64)) + head * Offset((N * 64)) +
        sg * Offset(64) + (dim / 4) * Offset(1);
    Offset ks = batch * Offset((KH * N * 8)) + head * Offset((N * 8)) +
        sg * Offset(8) + (dim / 32) * Offset(1);
    Offset kb = batch * Offset((KH * N * 8)) + head * Offset((N * 8)) +
        sg * Offset(8) + (dim / 32) * Offset(1);
    Offset vs = batch * Offset((KH * N * 8)) + head * Offset((N * 8)) +
        sg * Offset(8) + (dim / 32) * Offset(1);
    Offset vb = batch * Offset((KH * N * 8)) + head * Offset((N * 8)) +
        sg * Offset(8) + (dim / 32) * Offset(1);

    uint t = sg;
    for (; t + (TK - 1) * NS < N; t += TK * NS) {
        uint kw[TK][2], vw[TK][2];
        float sk[TK], bk[TK], sv[TK], bv[TK];
        #pragma unroll
        for (uint r = 0; r < TK; ++r) {
            kw[r][0] = keys[ko + r * dk];
            kw[r][1] = keys[ko + r * dk + Offset(1)];
            vw[r][0] = values[vo + r * dv];
            vw[r][1] = values[vo + r * dv + Offset(1)];
            sk[r] = float(key_scales[ks + r * dks]);
            bk[r] = float(key_biases[kb + r * dkb]);
            sv[r] = float(value_scales[vs + r * dvs]);
            bv[r] = float(value_biases[vb + r * dvb]);
        }
        #pragma unroll
        for (uint r = 0; r < TK; ++r) {
            float k[8], v[8];
            #pragma unroll
            for (uint w = 0; w < 2; ++w) {
                #pragma unroll
                for (uint j = 0; j < 4; ++j) {
                    k[4 * w + j] = float((kw[r][w] >> (8 * j)) & 255);
                    v[4 * w + j] = float((vw[r][w] >> (8 * j)) & 255) * sv[r] + bv[r];
                }
            }
            #pragma unroll
            for (uint h = 0; h < HPT; ++h) {
                float score = 0;
                #pragma unroll
                for (uint j = 0; j < 8; ++j) score += q[h][j] * k[j];
                score = simd_sum(sk[r] * score + bk[r] * qsum[h]);
                const float nm = max(m[h], score);
                const float alpha = fast::exp(m[h] - nm);
                const float p = fast::exp(score - nm);
                z[h] = z[h] * alpha + p;
                m[h] = nm;
                #pragma unroll
                for (uint j = 0; j < 8; ++j) acc[h][j] = acc[h][j] * alpha + p * v[j];
            }
        }
        ko += TK * dk;
        vo += TK * dv;
        ks += TK * dks;
        kb += TK * dkb;
        vs += TK * dvs;
        vb += TK * dvb;
    }
    for (; t < N; t += NS) {
        const float sk = float(key_scales[ks]), bk = float(key_biases[kb]);
        const float sv = float(value_scales[vs]), bv = float(value_biases[vb]);
        float k[8], v[8];
        #pragma unroll
        for (uint w = 0; w < 2; ++w) {
            const uint kw = keys[ko + w * Offset(1)];
            const uint vw = values[vo + w * Offset(1)];
            #pragma unroll
            for (uint j = 0; j < 4; ++j) {
                k[4 * w + j] = float((kw >> (8 * j)) & 255);
                v[4 * w + j] = float((vw >> (8 * j)) & 255) * sv + bv;
            }
        }
        #pragma unroll
        for (uint h = 0; h < HPT; ++h) {
            float score = 0;
            #pragma unroll
            for (uint j = 0; j < 8; ++j) score += q[h][j] * k[j];
            score = simd_sum(sk * score + bk * qsum[h]);
            const float nm = max(m[h], score);
            const float alpha = fast::exp(m[h] - nm);
            const float p = fast::exp(score - nm);
            z[h] = z[h] * alpha + p;
            m[h] = nm;
            #pragma unroll
            for (uint j = 0; j < 8; ++j) acc[h][j] = acc[h][j] * alpha + p * v[j];
        }
        ko += dk;
        vo += dv;
        ks += dks;
        kb += dkb;
        vs += dvs;
        vb += dvb;
    }
    #pragma unroll
    for (uint h = 0; h < HPT; ++h) {
        if (lane == 0) {
            max_scores[h * NS + sg] = m[h];
            sum_scores[h * NS + sg] = z[h];
        }
    }
    threadgroup_barrier(mem_flags::mem_threadgroup);
    float factor[HPT], norm[HPT];
    #pragma unroll
    for (uint h = 0; h < HPT; ++h) {
        const float lm = lane < NS ? max_scores[h * NS + lane] : -MAXFLOAT;
        const float gm = simd_max(lm);
        factor[h] = lane < NS ? fast::exp(lm - gm) : 0;
        norm[h] = simd_sum(lane < NS ? sum_scores[h * NS + lane] * factor[h] : 0);
    }
    // Transpose partial vectors in threadgroup memory. Each SIMD then reduces
    // NS partials for one output lane. MW dimensions share each barrier pair.
    #pragma unroll
    for (uint j0 = 0; j0 < 8; j0 += MW) {
        #pragma unroll
        for (uint h = 0; h < HPT; ++h) {
            #pragma unroll
            for (uint j = 0; j < MW; ++j) {
                scratch[((h * MW + j) * 32 + lane) * NS + sg] = acc[h][j0 + j];
            }
        }
        threadgroup_barrier(mem_flags::mem_threadgroup);
        #pragma unroll
        for (uint h = 0; h < HPT; ++h) {
            #pragma unroll
            for (uint dl = sg; dl < 32; dl += NS) {
                #pragma unroll
                for (uint j = 0; j < MW; ++j) {
                    const float value = lane < NS ?
                        scratch[((h * MW + j) * 32 + dl) * NS + lane] : 0;
                    const float result = simd_sum(value * factor[h]);
                    if (lane == 0) out[(bh * HPT + h) * 256 + dl * 8 + j0 + j] =
                        T(norm[h] > 0 ? result / norm[h] : 0);
                }
            }
        }
        threadgroup_barrier(mem_flags::mem_threadgroup);
    }
};
run(int(0));
"""

_MERGE = r"""
const uint d = thread_position_in_grid.x;
const uint h = thread_position_in_grid.y;
float m = -MAXFLOAT;
for (uint b = 0; b < S; ++b) m = max(m, maxs[h * S + b]);
float z = 0, o = 0;
for (uint b = 0; b < S; ++b) {
    const uint row = h * S + b;
    const float weight = fast::exp(maxs[row] - m);
    z += sums[row] * weight;
    o += partials[row * 256 + d] * weight;
}
out[h * 256 + d] = T(z > 0 ? o / z : 0);
"""
